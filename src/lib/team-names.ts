const lower = (s: string) => s.toLocaleLowerCase("tr");
// Aramada kullanılır: Türkçe addan veritabanındaki ada
const COUNTRY_ENTRIES = Object.entries(COUNTRIES).map(([en, tr]) => ({ en, trLower: lower(tr) }));

// "Latvia" → "Letonya"; "Germany U21" → "Almanya U21"; kulüp adları değişmez
export function trTeam(name: string): string;
export function trTeam(name: string | null): string | null;
export function trTeam(name: string | null): string | null {
  if (!name) return name;
  const direct = COUNTRIES[name];
  if (direct) return direct;
  const youth = name.match(/^(.+?) (U\d{2})$/);
  if (youth && COUNTRIES[youth[1]]) return `${COUNTRIES[youth[1]]} ${youth[2]}`;
  return name;
}

// Ülke adı (oyuncunun uyruğu, lig ülkesi)
export const trCountry = trTeam;

export function trLeague(name: string): string {
  return LEAGUES[name] ?? name;
}

// Türkçe yazılan aramaya ("alman", "letonya") uyan ülkelerin veritabanındaki adları
export function teamNamesMatching(query: string): string[] {
  const q = lower(query.trim());
  if (q.length < 2) return [];
  return COUNTRY_ENTRIES.filter((c) => c.trLower.includes(q)).map((c) => c.en);
}
